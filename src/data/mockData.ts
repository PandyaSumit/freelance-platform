// Helper function to get project by ID
export const getProjectById = (id: string): Project | undefined => {
  return mockProjects.find((p) => p.id === id);
};

// Helper function to get client by ID
export const getClientById = (id: string): Client | undefined => {
  return mockClients.find((c) => c.id === id);
};

// Helper function to get invoices by project
export const getInvoicesByProject = (projectId: string): Invoice[] => {
  return mockInvoices.filter((i) => i.projectId === projectId);
};

// Helper function to get deliverables by project
export const getDeliverablesByProject = (projectId: string): Deliverable[] => {
  return mockDeliverables.filter((d) => d.projectId === projectId);
};

// Helper function to get activities by project
export const getActivitiesByProject = (projectId: string): Activity[] => {
  return mockActivities.filter((a) => a.projectId === projectId);
};
